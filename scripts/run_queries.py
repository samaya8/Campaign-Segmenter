"""Day 2: run every query in sql/queries.sql against the campaign database.

Queries are separated by "-- @query QNN: title" lines. Each one is run on a
read-only connection (the original database is never modified) and printed
with pandas. Pass --markdown to write the outputs to reports/query_outputs.md.

Usage:
    python scripts/run_queries.py              # print all results
    python scripts/run_queries.py Q04 Q10      # print selected queries
    python scripts/run_queries.py --markdown   # also save reports/query_outputs.md
"""

import re
import sqlite3
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = ROOT / "data" / "raw" / "marketing_campaigns.sqlite"
SQL_PATH = ROOT / "sql" / "queries.sql"
MD_PATH = ROOT / "reports" / "query_outputs.md"

QUERY_HEADER = re.compile(r"^-- @query (Q\d+): (.+)$", re.MULTILINE)


def load_queries(path: Path = SQL_PATH) -> list[tuple[str, str, str]]:
    """Return [(query_id, title, sql), ...] in file order."""
    text = path.read_text(encoding="utf-8")
    headers = list(QUERY_HEADER.finditer(text))
    queries = []
    for i, m in enumerate(headers):
        end = headers[i + 1].start() if i + 1 < len(headers) else len(text)
        queries.append((m.group(1), m.group(2).strip(), text[m.end():end].strip()))
    return queries


def connect_readonly(path: Path = DB_PATH) -> sqlite3.Connection:
    if not path.exists():
        raise SystemExit(f"Database not found at {path}. See README 'Day 2' for download steps.")
    return sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)


def run_query(conn: sqlite3.Connection, sql: str) -> pd.DataFrame:
    return pd.read_sql_query(sql, conn)


def main(argv: list[str]) -> None:
    write_md = "--markdown" in argv
    wanted = {a.upper() for a in argv if not a.startswith("--")}
    pd.set_option("display.width", 200)
    pd.set_option("display.max_columns", 20)
    pd.set_option("display.max_rows", 200)

    conn = connect_readonly()
    md = ["# Day 2 query outputs", "", "Generated by `python scripts/run_queries.py --markdown`.", ""]
    for qid, title, sql in load_queries():
        if wanted and qid not in wanted:
            continue
        df = run_query(conn, sql)
        print(f"\n=== {qid}: {title} ({len(df)} rows) ===")
        print(df.to_string(index=False) if len(df) else "(no rows)")
        md += [f"## {qid}: {title}", "", f"{len(df)} rows", ""]
        md += [df.to_markdown(index=False, floatfmt=",.2f") if len(df) else "_(no rows)_", ""]
    conn.close()

    if write_md:
        MD_PATH.parent.mkdir(exist_ok=True)
        MD_PATH.write_text("\n".join(md), encoding="utf-8")
        print(f"\nSaved {MD_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1:])
